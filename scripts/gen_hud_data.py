#!/usr/bin/env python3
"""Turns the files listed in src/hud.rc (name RCDATA "path") into src/hud_data.h, so the DLL can be built
without a resource compiler (zig cc has none). Run it again after changing a HUD file, sound or the flame XML:
    python3 scripts/gen_hud_data.py
"""
import os, re, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rc = open(os.path.join(root, 'src', 'hud.rc'), encoding='utf-8').read()
items = re.findall(r'^(\w+)\s+RCDATA\s+"([^"]+)"', rc, re.M)
out = ['// Generated by scripts/gen_hud_data.py from src/hud.rc - do not edit.\n#pragma once\n#include <cstddef>\n\n']
table = []
for i, (name, rel) in enumerate(items):
    data = open(os.path.normpath(os.path.join(root, 'src', rel)), 'rb').read()
    out.append('static const unsigned char k_emb_%d[] = {\n' % i)
    for a in range(0, len(data), 32):
        out.append(','.join(str(b) for b in data[a:a + 32]) + ',\n')
    out.append('0};\n')
    table.append('    {"%s", k_emb_%d, %d},\n' % (name, i, len(data)))
out.append('\nstruct EmbeddedFile { const char* name; const unsigned char* data; size_t size; };\n')
out.append('static const EmbeddedFile k_embedded_files[] = {\n' + ''.join(table) + '};\n')
open(os.path.join(root, 'src', 'hud_data.h'), 'w').write(''.join(out))
print('hud_data.h:', len(items), 'files')
